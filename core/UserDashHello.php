    /**
     * @return array{hello:string,hint:string,slot:string,hour:int}
     */
    public static function pick($displayName)
    {
        $name = trim((string) $displayName);
        if ($name === '') {
            $name = '用户';
        }
        $hour = (int) date('G');
        $slot = self::slotMeta($hour);
        $helloTpl = self::pickOne($slot['hellos']);
        $hint = self::pickOne($slot['hints']);
        $hello = str_replace('{name}', $name, $helloTpl);
        return array(
            'hello' => $hello,
            'hint'  => $hint,
            'slot'  => $slot['id'],
            'hour'  => $hour,
        );
    }

    /**
     * 2 小时一段：0-1 … 22-23
     *
     * @param int $hour
     * @return array{id:string,hellos:string[],hints:string[]}
     */
    private static function slotMeta($hour)
    {
        $hour = max(0, min(23, (int) $hour));
        $start = $hour - ($hour % 2);
        $map = self::pools();
        $id = sprintf('%02d-%02d', $start, $start + 1);
        if (!isset($map[$id])) {
            $id = '22-23';
        }
        return $map[$id];
    }

    /**
     * @param string[] $list
     * @return string
     */
    private static function pickOne(array $list)
    {
        if (!$list) {
            return '';
        }
        try {
            $i = random_int(0, count($list) - 1);
        } catch (Exception $e) {
            $i = mt_rand(0, count($list) - 1);
        }
        return (string) $list[$i];
    }

